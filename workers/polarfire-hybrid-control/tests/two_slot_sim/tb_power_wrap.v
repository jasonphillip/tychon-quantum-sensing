// tb_power_wrap.v — SmartPower workload-VCD testbench for the two-slot
// pid_subsystem, with a scope hierarchy that MIRRORS the placed netlist.
//
// Why the shims exist: the placed netlist's PID path is
//   MPFS_ICICLE_KIT_BASE_DESIGN/FIC_0_PERIPHERALS_1/u_pid_subsystem/...
// The 2026-05-17/06-21 annotation attempts dumped a VCD whose top scope was
// the standalone nv_pid_top_top, so smartpower_import_vcd matched 0.00% of
// pins. Here two pass-through shim modules are INSTANTIATED under the names
// `MPFS_ICICLE_KIT_BASE_DESIGN` and `FIC_0_PERIPHERALS_1` so the VCD scope
// path lines up 1:1 with the netlist hierarchy (VCD records instance names,
// not module names).
//
// Stimulus (the documented representative workload, via REAL AXI transactions
// rather than hierarchical force): gains via M0, then the 1000-row chirped
// ODMR error trace (sim/stimulus/odmr_representative_trace.hex, generated by
// trace_to_hex.py) via M1 error/u_ai writes + M0 start pulses. vbx_output_valid
// pulses every ~4000 cycles (~32 us: the measured on-kit V250 completion
// median) so vbx_pulse_gen + watchdog_timer toggle realistically; with the
// r12_s31 netlist's 62.5e6-cycle watchdog the timeout stays 0 throughout —
// the realistic AI-active operating mode.
//
// Clock: 8 ns period = 125 MHz (the PID fabric domain; the old .do's 5 ns
// was a 200 MHz-assumption error).
//
// 64-bit-bus lane rule: byte offset bit[2]=0 -> low lane, bit[2]=1 -> high lane.

